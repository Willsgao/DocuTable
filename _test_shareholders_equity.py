def run_test(name, table):
    print(f"\n{'='*80}")
    print(f"【测试】{name}")
    print(f"{'='*80}")
    print("原始表格:")
    for i, row in enumerate(table):
        print(f"  [{i:2d}] {row}")

    repaired, info = repair_table_rules(table)
    print(f"\n  needed={info['needed']}, reason={info['reason']}")
    print(f"  rows: {info['original_rows']} -> {info['repaired_rows']}")
    print(f"  data_cols={info['data_cols']}")
    print(f"  steps={info['steps']}")
    print(f"\n修复后:")
    for i, row in enumerate(repaired):
        print(f"  [{i:2d}] {row}")
    return repaired, info


