# -*- coding: utf-8 -*-
"""分析理财产品表的表头结构"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

# 用户给的原始表格，按 tab 分隔
raw = [
    "74\t.00%，对公理财产品余额109.93亿元，占比26.00%。",
    "\t人寿旗下资管子公司资产管理业务规模分别为1.60万",
    "亿元、1.47万亿元、1.45万亿元、0.65万亿元、0.36万",
    "亿元。",
    "以下为报告期内本集团理财产品发行、到期和存续情况。",
    "\t\t\t2024年",
    "\t2023年12月31日\t\t产品发行募集\t\t产品到期兑付\t\t2024年12月31日",
    "（人民币百万元，期数除外）\t\t期数\t\t金额\t期数\t金额\t期数\t金额",
    "建信理财\t\t1,100\t1,499,121\t\t676\t3,315,531\t781\t3,215,927\t995\t1,598,725",
    "本行\t\t2\t79,443\t\t–\t101,819\t–\t138,974\t2\t42,288",
    "总额\t\t1,102\t1,578,564\t\t676\t3,417,350\t781\t3,354,901\t997\t1,641,013",
]

# 解析成 2D 数组
table = []
for line in raw:
    row = line.split('\t')
    table.append([c.strip() for c in row])

print("原始表格（tab分隔后）:")
for i, row in enumerate(table):
    print(f"[{i:2d}] ({len(row)} cols) {row}")

print()
print("=" * 80)
print("数据区域分析:")
print("=" * 80)

# 数据行是最后3行（建信理财、本行、总额）
for i in range(len(table)-3, len(table)):
    print(f"[{i:2d}] {table[i]}")

print()
print("数据列结构:")
print("  col 0: 机构名称（建信理财/本行/总额）")
print("  col 1-2: 2023年12月31日（期数+金额）")
print("  col 3-4: 产品发行募集（期数+金额）")
print("  col 5-6: 产品到期兑付（期数+金额）")
print("  col 7-8: 2024年12月31日（期数+金额）")
print("  共9列 = 1行标签列 + 4组×2子列")

print()
print("=" * 80)
print("表头层级拆解:")
print("=" * 80)
print("""
层级1: 【2024年】 — 年份标签，标注整个报告期
层级2: 【2023年12月31日 | 产品发行募集 | 产品到期兑付 | 2024年12月31日】 — 4个时间/事件组
层级3: 【期数 | 金额 | 期数 | 金额 | 期数 | 金额 | 期数 | 金额】 — 每个组下2个子列

第一列的【（人民币百万元，期数除外）】是单位说明，属于行标签列的表头
""")

print()
print("=" * 80)
print("修复后理想的表头结构（9列，从上到下3层表头）:")
print("=" * 80)

ideal = [
    # col0  col1     col2     col3     col4     col5     col6     col7     col8
    ['',    '2024年', '2024年', '2024年', '2024年', '2024年', '2024年', '2024年', '2024年'],
    ['（人民币百万元，期数除外）', '2023年12月31日', '2023年12月31日', '产品发行募集', '产品发行募集', '产品到期兑付', '产品到期兑付', '2024年12月31日', '2024年12月31日'],
    ['',    '期数',   '金额',   '期数',   '金额',   '期数',   '金额',   '期数',   '金额'],
]

for i, row in enumerate(ideal):
    print(f"[{i}] {row}")

print()
print("数据行（3行）:")
data_rows = [
    ['建信理财', '1,100', '1,499,121', '676', '3,315,531', '781', '3,215,927', '995', '1,598,725'],
    ['本行',     '2',     '79,443',   '–',   '101,819',  '–',   '138,974',  '2',   '42,288'],
    ['总额',     '1,102', '1,578,564', '676', '3,417,350', '781', '3,354,901', '997', '1,641,013'],
]
for row in data_rows:
    print(f"     {row}")

print()
print("=" * 80)
print("关键修复点:")
print("=" * 80)
print("1. 【2024年】在原始第5行，只有1个tab位在右侧，需要判断它是否是年份标签")
print("   → 它在最上层表头，应该向右填充跨所有数据列（col1~col8）")
print("2. 【2023年12月31日/产品发行募集/产品到期兑付/2024年12月31日】在原始第6行")
print("   → 每个覆盖2个子列（期数+金额）")
print("3. 底层表头定义了9列: 行标签列 + 4组×2子列")
print("4. 【（人民币百万元，期数除外）】在col0，是单位说明而非列名")
